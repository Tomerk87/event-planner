const browser = await chromium.launch()
const page = await browser.newPage({ deviceScaleFactor: SCALE })
const entries: string[] = []
for (const drawing of drawings) {
  await page.setContent(
    `<html><body style="margin:0;background:transparent">
      <svg xmlns="http://www.w3.org/2000/svg" width="${drawing.width}" height="${drawing.height}" viewBox="0 0 ${drawing.width} ${drawing.height}" style="display:block">${drawing.svg}</svg>
    </body></html>`,
  )
  const png = await page
    .locator('svg')
    .screenshot({ omitBackground: true, type: 'png' })
  entries.push(`  /** ${drawing.comment} */
  ${drawing.name}: {
    width: ${drawing.width},
    height: ${drawing.height},
    png: '${png.toString('base64')}',
  },`)
}
await browser.close()

const target = path.resolve(
  import.meta.dirname,
  '../../backend/src/email/images.ts',
)
writeFileSync(
  target,
  `// Generated by frontend/scripts/email-images.ts; do not edit by hand.

export interface EmailPicture {
  /** The size it is shown at, in CSS pixels; the PNG is drawn ${SCALE} times larger. */
  width: number
  height: number
  /** The PNG, in base64. */
  png: string
}

export const PICTURES = {
${entries.join('\n')}
} satisfies Record<string, EmailPicture>

export type PictureName = keyof typeof PICTURES
`,
)
console.log(`Wrote ${drawings.length} pictures to ${target}`)
