/**
 * Writes src/shared/timeZoneCountries.ts: the country of each time zone, so
 * a time zone can be found by its country's name (D104). The source is the
 * IANA time zone database's zone.tab, as installed with the operating
 * system; run again when it changes:
 *
 *   node scripts/time-zone-countries.ts [/usr/share/zoneinfo/zone.tab]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const source = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab'
const entries = readFileSync(source, 'utf8')
  .split('\n')
  .filter((line) => line.trim() !== '' && !line.startsWith('#'))
  .map((line) => {
    const [country, , zone] = line.split('\t')
    return [zone!, country!] as const
  })
  .sort(([a], [b]) => a.localeCompare(b))

const output = path.join(
  import.meta.dirname,
  '../src/shared/timeZoneCountries.ts',
)
writeFileSync(
  output,
  `// Generated by scripts/time-zone-countries.ts from the IANA time zone
// database (zone.tab). Do not edit by hand.

/** The ISO 3166 country code of each time zone that belongs to a country. */
export const TIME_ZONE_COUNTRIES: Readonly<Record<string, string>> = {
${entries.map(([zone, country]) => `  '${zone}': '${country}',`).join('\n')}
}
`,
)
console.log(`Wrote ${entries.length} time zones to ${output}`)
